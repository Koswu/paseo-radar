#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const collectorsSrcDir = join(rootDir, "scripts", "collectors");
const targetFile = join(rootDir, "server", "collector-seeds.ts");

const DEFAULT_PROVIDERS_CONFIG = {
  defaultRepoPath: "",
  issueTeamPrefixes: [],
  providers: {
    github: {
      enabled: false,
      lifecycle: "oneshot",
      config: {
        hostname: "github.com",
        repoPaths: {},
      },
    },
    gitlab: {
      enabled: false,
      lifecycle: "oneshot",
      config: {
        hostname: "",
        repoPaths: {},
      },
    },
    linear: {
      enabled: false,
      lifecycle: "oneshot",
      config: {
        orgSlug: "",
        profile: "",
      },
    },
    slack: {
      enabled: false,
      lifecycle: "oneshot",
      config: {
        lookbackDays: 4,
        noisyChannels: ["general", "random"],
      },
    },
  },
};

const DEFAULT_COLLECTORS_CONFIG = {
  defaultRepoPath: "",
  issueTeamPrefixes: [],
  github: {
    enabled: false,
    hostname: "github.com",
    repoPaths: {},
  },
  gitlab: {
    enabled: false,
    hostname: "",
    repoPaths: {},
  },
  linear: {
    enabled: false,
    orgSlug: "",
    profile: "",
  },
  slack: {
    enabled: false,
    lookbackDays: 4,
    noisyChannels: ["general", "random"],
  },
};

async function buildContent() {
  const specMd = await readFile(join(collectorsSrcDir, "SPEC.md"), "utf8");
  const sdkPy = await readFile(join(collectorsSrcDir, "radar_provider.py"), "utf8");
  const entries = await readdir(collectorsSrcDir, { withFileTypes: true });
  const pyNames = entries
    .filter(
      (e) =>
        e.isFile() &&
        e.name.endsWith(".py") &&
        !e.name.startsWith(".") &&
        !e.name.startsWith("_") &&
        e.name !== "radar_provider.py",
    )
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b));

  const scripts = [];
  for (const filename of pyNames) {
    const content = await readFile(join(collectorsSrcDir, filename), "utf8");
    scripts.push({ filename, content });
  }

  const lines = [
    "// Auto-generated by scripts/sync-collector-seeds.mjs — DO NOT EDIT DIRECTLY.",
    "// Edit files under scripts/collectors/ and run `npm run sync-seeds`.",
    "",
    `export const RADAR_PROVIDER_SDK_PY = ${JSON.stringify(sdkPy)};`,
    "",
    `export const COLLECTOR_SPEC_MD = ${JSON.stringify(specMd)};`,
    "",
    `export const DEFAULT_PROVIDERS_CONFIG = ${JSON.stringify(DEFAULT_PROVIDERS_CONFIG, null, 2)} as const;`,
    "",
    `export const DEFAULT_COLLECTORS_CONFIG = ${JSON.stringify(DEFAULT_COLLECTORS_CONFIG, null, 2)} as const;`,
    "",
    "export const SEED_COLLECTOR_SCRIPTS: ReadonlyArray<{ filename: string; content: string }> = [",
    ...scripts.map(
      (s) => `  { filename: ${JSON.stringify(s.filename)}, content: ${JSON.stringify(s.content)} },`,
    ),
    "];",
    "",
  ];
  return lines.join("\n");
}

const checkOnly = process.argv.includes("--check");
const generated = await buildContent();

if (checkOnly) {
  const current = await readFile(targetFile, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      "server/collector-seeds.ts is out of sync with scripts/collectors/. Run `npm run sync-seeds`.",
    );
    process.exit(1);
  }
  console.log("collector-seeds.ts is in sync.");
} else {
  await writeFile(targetFile, generated, "utf8");
  console.log(`Updated ${targetFile}`);
}
